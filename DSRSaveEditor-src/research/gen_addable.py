#!/usr/bin/env python3
"""Regenerates source/goods_data.inc and source/addable_data.inc from research/param_items.csv
(decoded from the game's own EquipParam tables). Run: python3 -I research/gen_addable.py

Sort key rule (checked against 1,733 entries in 6 real Switch saves, all exceptions explained):
  goods and rings: key = sortId;  weapons and armor: key = sortId * 100.
An item that the game creates by transforming another one (infusion, boss-soul weapon, Estus upgrade)
keeps the SOURCE item's handle, so a transformed weapon "X [Source]" is given Source's key."""
import csv, os, re, collections
here = os.path.dirname(os.path.abspath(__file__))
R = list(csv.DictReader(open(os.path.join(here, "param_items.csv"))))
by = collections.defaultdict(dict)
for r in R: by[r["category"]][int(r["id"])] = r

def clean(r):
    n = r["name"]
    return bool(n) and n not in ("?", "None") and not re.match(r"\[?Unused", n) and "[Ghost]" not in n and "Design Content" not in n

def q(s): return s.replace("\\", "\\\\").replace('"', '\\"')

# ---- goods: stackable consumables/materials (maxNum from the game) and spells (stored as x1) ----
ESTUS = set(range(200, 216))
goods = []
for i, r in sorted(by["goods"].items()):
    if not clean(r) or i in ESTUS or i == 350: continue
    t, mx, key = int(r["goodsType"]), int(r["maxNum"]), int(r["sortId"])
    if key <= 0: continue
    if r["name"].startswith("[Unused]"): continue
    if t in (0, 2): goods.append((i, r["name"], key, mx, 0))
    elif t == 5: goods.append((i, r["name"], key, 1, 0))
    elif t == 1: goods.append((i, r["name"], key, 1, 1))  # key item: lives in slots 0-63
goods.sort(key=lambda g: g[2])
assert len({g[2] for g in goods}) == len(goods), "duplicate goods keys"
assert all(r not in goods for r in [])

rings = sorted((int(r["sortId"]), i, r["name"]) for i, r in by["ring"].items() if clean(r) and int(r["sortId"]) > 0)
# Armor sets that exist in the tables but were never meant to be owned (Elite Cleric, Mage Smith).
CUT_ARMOR = set(range(650000, 654000, 1000)) | set(range(370000, 374000, 1000))
def _armor(want_cut):
    return sorted((int(r["sortId"]) * 100, i, r["name"], int(r["durabilityMax"])) for i, r in by["armor"].items()
               if (i in CUT_ARMOR) == want_cut and clean(r) and i % 100 == 0 and int(r["sortId"]) > 0 and int(r["durabilityMax"]) > 0)
armor = _armor(False); cut = _armor(True)

# ---- weapons: every +0 weapon except ammunition (categories 13, 14) and fists ----
W = by["weapon"]
base = {r["name"]: int(r["sortId"]) for i, r in W.items() if i % 1000 == 0 and "[" not in r["name"]}
weapons = []; skipped = []
for i, r in sorted(W.items()):
    ammo = int(r["weaponCategory"]) in (13, 14)
    if i % 1000 or not clean(r) or i == 900000 or (not ammo and int(r["durabilityMax"]) <= 0): continue
    n = r["name"]; m = re.search(r"\[(.+)\]$", n)
    if m:  # transformed weapon: keeps the source weapon's handle key
        if m[1] not in base: skipped.append(n); continue
        key = base[m[1]] * 100
    else:
        key = int(r["sortId"]) * 100
    if key <= 0: continue
    weapons.append((key, i, n, int(r["durabilityMax"]), 999 if ammo else 1))
weapons.sort()
# Transformed weapons share their source's key; the table needs unique (tag,key) only for the tests'
# sanity check, so dedupe is NOT applied (the game itself creates such duplicates).

with open(os.path.join(here, "..", "source", "goods_data.inc"), "w") as f:
    f.write("// Generated by research/gen_addable.py from research/param_items.csv - do not edit by hand.\n// GOODS(id, name, sortKey, maxStack, isKeyItem)\n")
    for i, n, k, mx, kd in goods: f.write('GOODS(%d, "%s", %d, %d, %d)\n' % (i, q(n), k, mx, kd))
with open(os.path.join(here, "..", "source", "cut_data.inc"), "w") as f:
    f.write("// Generated by research/gen_addable.py: unobtainable armor, hidden behind ZL+ZR on the Add screen.\n")
    for k, i, n, d in cut: f.write('    {0x10000000u, %d, "%s", %d, %d, 1, 0},\n' % (i, q(n), k, d))
with open(os.path.join(here, "..", "source", "cut_count.h"), "w") as f:
    f.write("#define DSR_CUT_COUNT %d\n" % len(cut))
with open(os.path.join(here, "..", "source", "addable_data.inc"), "w") as f:
    f.write("// Generated by research/gen_addable.py from research/param_items.csv - do not edit by hand.\n// {tag, id, name, sortKey, durability, maxStack, keyItem}\n")
    for k, i, n in rings: f.write('    {0x20000000u, %d, "%s", %d, 0, 1, 0},\n' % (i, q(n), k))
    for k, i, n, d in armor: f.write('    {0x10000000u, %d, "%s", %d, %d, 1, 0},\n' % (i, q(n), k, d))
    for k, i, n, d, mx in weapons: f.write('    {0x00000000u, %d, "%s", %d, %d, %d, 0},\n' % (i, q(n), k, d, mx))
print("goods", len(goods), "rings", len(rings), "armor", len(armor), "weapons", len(weapons), "skipped transforms", skipped)
